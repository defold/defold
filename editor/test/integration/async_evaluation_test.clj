(g/defnode LayoutTestNode
  (property trivial-gui-scene-info g/Any (default {:current-layout "Landscape"}))
  (property layout->prop->override g/Any (default {})))

;; GUI reset steps can be generated by editor scripts on a worker. Their graph
;; reads must wait for the transaction context, including shell materialization.
(deftest background-gui-property-reset-test
  (doseq [reset-property [gui/basic-layout-property-clear-in-current-layout
                          (partial gui/layout-property-edit-type-clear-in-current-layout nil)
                          (partial gui/layout-property-edit-type-clear-in-current-layout
                                   (fn property-changes [_evaluation-context _node-id prop-kw _old _new]
                                     {prop-kw nil}))]]
    (let [shell (ui/run-now
                  (let [[shell] (g/take-node-ids 1)]
                    (g/transact
                      (g/add-node
                        (g/construct-shell LayoutTestNode {:_node-id shell}
                          (fn materialize-node [self _evaluation-context]
                            (g/set-property self :layout->prop->override {"Landscape" {:value 7}})))))
                    shell))]
      (ui/run-now
        (let [basis (g/now)
              tx-data (deref (future (reset-property shell :value)) 10000 ::timed-out)]
          (is (identical? basis (g/now)))
          (g/transact tx-data)
          (is (not (in/shell-node? (g/node-by-id (g/now) shell))))
          (is (nil? (get-in (g/raw-property-value (g/now) shell :layout->prop->override)
                            ["Landscape" :value]))))))))

;; Console HTTP requests evaluate on the server thread and must defer shell
;; materializations to the UI thread instead of using an implicit context.
(deftest console-request-materialization-test
  (let [[console-node request-handler]
        (ui/run-now
          (let [[console-node] (g/take-node-ids 1)
                console-view (g/make-node! view/WorkbenchView)]
            (g/transact
              [(g/add-node
                 (g/construct-shell console/ConsoleNode {:_node-id console-node}
                   (fn materialize-console [self _evaluation-context]
                     (g/set-property self :modified-lines ["Background read"]))))
               (g/connect console-node :_node-id console-view :resource-node)])
            [console-node (get-in (console/routes console-view) ["/console" "GET"])]))]
    (ui/run-now
      (let [basis (g/now)
            response (deref (future (request-handler {})) 10000 ::timed-out)]
        (is (= 200 (:status response)))
        (is (= {"lines" ["Background read"] "regions" []}
               (json/read-str (String. ^bytes (:body response) "UTF-8"))))
        (is (identical? basis (g/now)))))
    (ui/run-now
      (is (= ["Background read"] (g/raw-property-value (g/now) console-node :modified-lines))))))

;; Serving HTML5 builds must read unloaded project settings without committing
;; them from the HTTP thread or waiting for the UI queue to drain.
(deftest html5-request-materialization-test
  (let [[settings-node request-handler]
        (ui/run-now
          (let [workspace (test-util/setup-scratch-workspace! "test/resources/empty_project")
                project (test-util/setup-project! workspace)
                output-file (io/file (workspace/build-html5-path workspace) "__htmlLaunchDir" "Emptyproject" "index.html")]
            (io/make-parents output-file)
            (spit output-file "HTML5 response")
            [(project/get-resource-node project "/game.project")
             (get-in (bob/routes project) ["/html5/{*path}" "GET"])]))]
    (ui/run-now
      (is (in/shell-node? (g/node-by-id (g/now) settings-node)))
      (let [basis (g/now)
            response (deref (future (request-handler {:path-params {:path "index.html"}})) 10000 ::timed-out)]
        (is (= 200 (:status response)))
        (is (= "HTML5 response" (slurp (.toFile ^Path (:body response)))))
        (is (identical? basis (g/now)))))
    (ui/run-now
      (is (not (in/shell-node? (g/node-by-id (g/now) settings-node)))))))

;; A build's supplied context must include shared build-server settings, without
;; a nested implicit context committing them on the background build thread.
(deftest html5-build-options-materialization-test
  (let [[project settings-node prefs]
        (ui/run-now
          (let [workspace (test-util/setup-scratch-workspace! "test/resources/empty_project")
                settings-file (io/file (workspace/project-directory workspace) "project.shared_editor_settings")]
            (spit settings-file "[extensions]\nbuild_server = https://build.example.com\n")
            (workspace/resource-sync! workspace)
            (let [project (test-util/setup-project! workspace)]
              [project
               (project/get-resource-node project "/project.shared_editor_settings")
               (prefs/make :scopes {:global (io/file (workspace/project-directory workspace) ".internal" "test.editor_settings")}
                           :schemas [:default])])))]
    (ui/run-now
      (is (in/shell-node? (g/node-by-id (g/now) settings-node)))
      (let [basis (g/now)
            options (deref (future
                             (ea/with-auto-evaluation-context evaluation-context
                               (bob/build-html5-bob-options project prefs evaluation-context)))
                           10000 ::timed-out)]
        (is (= "https://build.example.com" (get options "build-server")))
        (is (identical? basis (g/now)))))
    (ui/run-now
      (is (not (in/shell-node? (g/node-by-id (g/now) settings-node)))))))

;; Saving and reloading can be initiated by editor-script worker threads. Their
;; graph reads and plugin updates must obey the same UI-thread commit guard.
(deftest background-save-and-reload-test
  (let [[workspace project]
        (ui/run-now
          (let [workspace (test-util/setup-scratch-workspace! "test/resources/empty_project")]
            [workspace (test-util/setup-project! workspace)]))
        save-completed (promise)
        reload-completed (promise)]
    @(future
       (disk/async-save! progress/null-render-progress! progress/null-render-progress!
                         project/dirty-save-data project nil save-completed))
    (is (true? (deref save-completed 10000 ::timed-out)))
    @(future
       (disk/async-reload! progress/null-render-progress! workspace [] nil reload-completed))
    (is (true? (deref reload-completed 10000 ::timed-out)))))

;; Action completion must include prerequisite materializations. Otherwise a
;; settings update can silently target a child that only exists in its context.
(deftest background-editor-actions-materialize-before-transacting-test
  (let [[project settings-node]
        (ui/run-now
          (let [workspace (test-util/setup-scratch-workspace! "test/resources/empty_project")
                project (test-util/setup-project! workspace)]
            [project (project/get-resource-node project "/game.project")]))
        rt (rt/make)
        lua-actions (rt/->lua [{:action "set"
                                :node_id "/game.project"
                                :property "project.title"
                                :value "Action title"}])]
    (is (in/shell-node? (g/node-by-id (g/now) settings-node)))
    @(actions/perform! lua-actions project {:rt rt})
    (ui/run-now
      (is (= "Action title" (get (g/node-value settings-node :settings-map) ["project" "title"]))))))

;; A completed Lua call must publish the nodes loaded by its final evaluation
;; segment, including after suspension, before a returned action uses their IDs.
(deftest suspending-lua-completion-materializes-returned-nodes-test
  (doseq [suspend-first [false true]]
    (let [[project gui-node]
          (ui/run-now
            (let [workspace (test-util/setup-scratch-workspace! "test/resources/editor_extensions/properties_project")
                  project (test-util/setup-project! workspace)]
              [project (project/get-resource-node project "/main/test.gui")]))
          rt (rt/make :env {"get_nodes" (rt/lua-fn [{:keys [evaluation-context]}]
                                          ((graph/ext-value-getter gui-node "nodes" project evaluation-context)))
                            "suspend" (rt/suspendable-lua-fn [_] nil)})
          lua-fn (->> (rt/read "return function(suspend_first)
                                  if suspend_first then suspend() end
                                  return {{action='set', node_id=get_nodes()[1],
                                           property='position', value={1,2,3}}}
                                end")
                      (rt/bind rt)
                      (rt/invoke-immediate-1 rt))]
      (is (in/shell-node? (g/node-by-id (g/now) gui-node)))
      (let [lua-actions @(rt/invoke-suspending-1 rt lua-fn (rt/->lua suspend-first))
            child-id (-> (rt/->clj rt actions/actions-coercer lua-actions)
                         first :node_id graph/editor-lookup->node-id)]
        (is (some? (g/node-by-id (g/now) child-id)))
        @(actions/perform! lua-actions project {:rt rt})
        (ui/run-now
          (is (= [1 2 3] (g/node-value child-id :position))))))))
