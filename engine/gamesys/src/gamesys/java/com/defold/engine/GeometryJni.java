package com.defold.engine;

/** Slice-9 geometry generated by the same C++ implementation as the engine. */
public final class GeometryJni {
    private GeometryJni() {}

    private static void ValidateParams(Geometry.Slice9Params params) {
        if (params == null)
            throw new IllegalArgumentException("Slice9Params must not be null");
        if (params.slice9 == null || params.slice9.length != 4)
            throw new IllegalArgumentException("slice9 must contain left, top, right and bottom margins");
        if ((params.flipHorizontal != 0 && params.flipHorizontal != 1) ||
            (params.flipVertical != 0 && params.flipVertical != 1))
            throw new IllegalArgumentException("Flip flags must be 0 or 1");
    }

    /** Returns 16 normalized XY pairs in row-major order, with the pivot subtracted. */
    public static float[] GenerateSlice9Positions(Geometry.Slice9Params params) {
        ValidateParams(params);
        EngineJni.Initialize();
        return GenerateSlice9PositionsInternal(params);
    }

    /**
     * Returns 16 UV pairs matching the position grid.
     * Texture dimensions are the original atlas dimensions in pixels.
     * texCoords contains unflipped bottom-left, top-left, top-right and bottom-right UV pairs.
     */
    public static float[] GenerateSlice9TexCoords(Geometry.Slice9Params params, float textureWidth,
                                                 float textureHeight, float[] texCoords) {
        ValidateParams(params);
        if (texCoords == null || texCoords.length != 8)
            throw new IllegalArgumentException("texCoords must contain four UV pairs");
        EngineJni.Initialize();
        return GenerateSlice9TexCoordsInternal(params, textureWidth, textureHeight, texCoords);
    }

    /** Returns a copy of the 54 indices describing the nine cells' triangles. */
    public static int[] GetSlice9Indices() {
        EngineJni.Initialize();
        return GetSlice9IndicesInternal();
    }

    private static native int[] GetSlice9IndicesInternal();
    private static native float[] GenerateSlice9PositionsInternal(Geometry.Slice9Params params);
    private static native float[] GenerateSlice9TexCoordsInternal(Geometry.Slice9Params params, float textureWidth,
                                                                 float textureHeight, float[] texCoords);
}
